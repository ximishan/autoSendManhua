import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import ExcelJS from 'exceljs';
import { openDatabase } from './test-db.mjs';

const root=process.cwd(), temp=fs.mkdtempSync(path.join(os.tmpdir(),'asm-v1-actions-'));
const db=openDatabase(path.join(temp,'data','app.db'));
const review=db.tasks.create({title:'待审核测试任务',content:'本地测试内容',selectedPlatforms:['baijiahao']});
db.tasks.finishJob(review.jobs[0],{success:true,canonicalUrl:'https://weibo.com/123/Abcd'});
db.tasks.finishJob(review.jobs[1],{success:true,resultStatus:'submitted',evidence:{submitted:true}});
db.tasks.setStatus(review.id,'awaiting_review');
const unknown=db.tasks.create({title:'提交结果待核对',content:'本地测试内容'});
db.tasks.updateJob(unknown.jobs[0].id,{status:'needs_action',phase:'submitting',error_code:'PUBLISH_UNCERTAIN'});
db.tasks.setStatus(unknown.id,'paused');db.close();
const file=path.join(temp,'import.xlsx');
const book=new ExcelJS.Workbook(), sheet=book.addWorksheet('任务');
sheet.columns=['title','content','resource_url','images','platforms','weibo_account'].map(key=>({key,header:key}));
sheet.addRow({title:'有效导入行',content:'测试正文',resource_url:'https://example.com',images:'',platforms:'',weibo_account:'test_weibo'});
sheet.addRow({title:'无效导入行',content:'测试正文',resource_url:'bad',images:'',platforms:'',weibo_account:'missing'});
await book.xlsx.writeFile(file);
const app=await electron.launch({args:[root],cwd:root,env:{...process.env,AUTO_SEND_MANHUA_ROOT:temp}});
const cases=[];
try {
  const page=await app.firstWindow();await page.route(/^https?:\/\//,r=>r.abort());
  await page.locator('[data-detail="'+review.id+'"]').waitFor();
  await page.locator('[data-page="create"]').click();
  await page.locator('[name="title"]').fill('从界面保存的任务');await page.locator('[name="content"]').fill('界面正文');
  await page.locator('#weibo-account').selectOption('test_weibo');await page.locator('#save-draft').click();
  await page.waitForFunction(()=>document.querySelector('#task-list').textContent.includes('从界面保存的任务'));
  let snapshot=await page.evaluate(()=>window.autoSend.snapshot());
  const created=snapshot.tasks.find(t=>t.title==='从界面保存的任务');assert.equal(created.status,'pending');
  cases.push('UI创建待执行任务');
  await page.locator('[data-pause="'+created.id+'"]').click();
  await page.waitForFunction(async id=>(await window.autoSend.getTask(id)).status==='paused',created.id);
  cases.push('UI暂停持久化');
  await page.locator('[data-detail="'+review.id+'"]').click();
  assert.match(await page.locator('#detail-content').innerText(),/已提交待审核/);
  const reviewJob=review.jobs[1].id;
  await page.locator('#result-'+reviewJob).fill('https://baijiahao.baidu.com/s?id=12345');
  await page.locator('[data-reconcile="'+reviewJob+'"]').click();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('核实'));
  assert.equal((await page.evaluate(id=>window.autoSend.getTask(id),review.id)).jobs[1].status,'submitted');
  await page.locator('#confirm-'+reviewJob).check();await page.locator('[data-reconcile="'+reviewJob+'"]').click();
  await page.waitForFunction(async id=>(await window.autoSend.getTask(id)).status==='completed',review.id);
  cases.push('待审核准确显示且人工确认后才记已发布');await page.locator('#close-detail').click();
  await page.locator('[data-detail="'+unknown.id+'"]').click();
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('[data-not-published="'+unknown.jobs[0].id+'"]').click();
  await page.waitForFunction(async id=>(await window.autoSend.getTask(id)).jobs[0].phase==='prepare',unknown.id);
  cases.push('确认未发布后只重新准备、不自动发帖');await page.locator('#close-detail').click();
  await page.locator('[data-page="settings"]').click();
  await page.locator('#setting-attempts').fill('3');await page.locator('#setting-delay').fill('2500');
  await page.locator('#setting-retention').fill('7');await page.locator('#save-settings').click();
  await page.waitForFunction(async()=>(await window.autoSend.getSetting('queue.intervalMs'))===2500);
  cases.push('设置保存');
  await app.evaluate(({dialog},input)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[input]});},file);
  await page.locator('[data-page="batch"]').click();await page.locator('#excel-import').click();
  await page.waitForFunction(()=>document.querySelector('#import-result').textContent.includes('错误 1'));
  assert.match(await page.locator('#import-result').innerText(),/创建 1 条/);
  cases.push('UI导入保留正确行并报告错误行');
  const output=path.join(temp,'export.xlsx');
  await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},output);
  await page.locator('[data-page="tasks"]').click();await page.locator('#export-results').click();
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('已导出'));
  const exported=new ExcelJS.Workbook();await exported.xlsx.readFile(output);
  assert.equal(exported.worksheets[0].rowCount,5);
  cases.push('UI导出文件可重新读取');
  const shots=path.join(root,'docs','screenshots');fs.mkdirSync(shots,{recursive:true});
  await page.screenshot({path:path.join(shots,'v1-task-center.png'),fullPage:true});
  console.log(JSON.stringify({passed:true,externalPublishing:false,isolatedData:true,cases,exportRows:4,screenshot:'docs/screenshots/v1-task-center.png'},null,2));
}finally{await app.close();}
